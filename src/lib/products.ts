export const PRODUCTS_BY_CATEGORY = PRODUCTS.reduce<Record<string, Product[]>>((acc, p) => {
  (acc[p.category] ??= []).push(p);
  return acc;
}, {});

export const productById = (id: string): Product | undefined => PRODUCTS.find((p) => p.id === id);
export const productBySlug = (slug: string): Product | undefined => PRODUCTS.find((p) => p.slug === slug);

/** True if a given variant label exists on this product's catalog entry. */
export const hasVariant = (productId: string, variantLabel: string): boolean =>
  productById(productId)?.variants.some((v) => v.label === variantLabel) ?? false;
